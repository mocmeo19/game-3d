"""
Eye styles from the MPFB library (plain python, needs Pillow):

    python3 mpfb/build_eyes.py

Writes public/models/eyes/<id>.webp (the eye atlas, same layout as the built-in one), <id>.icon.webp (the iris on its own, for the
picker) and src/constants/eyes.ts. Licences / authors come from the system_eye_materials packs.
"""
import glob, json, os, re
from PIL import Image, ImageDraw

DATA = os.path.expanduser('~/Library/Application Support/Blender/5.2/mpfb/data')
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'public', 'models', 'eyes')
os.makedirs(OUT, exist_ok=True)
CENTER = (0.705, 0.296)  # iris of the upper eye in the atlas
ICON = 96

meta = {}
for f in glob.glob(os.path.join(DATA, 'packs', 'system_eye_materials*.json')):
    meta.update(json.load(open(f)))


def texture_of(path):
    for line in open(path, encoding='utf-8', errors='ignore'):
        if line.startswith('diffuseTexture'):
            return os.path.join(os.path.dirname(path), line.split(None, 1)[1].strip())
    return None


def pretty(n):
    n = re.sub(r'^(bobby_03|callharvey3d|culturalibre|elvs|gpedroso|hatshj|mindfront|mtknife|nyloseth|sonntag78|spamrakuen|titleknown|wojackowl)[_-]', '', n)
    n = re.sub(r'_?eyes?(_toon)?$', '', n) or n
    return re.sub(r'[_-]+', ' ', n).strip().capitalize()


MAT = os.path.join(DATA, 'eyes', 'materials')
items = []
for entry in sorted(os.listdir(MAT)):
    p = os.path.join(MAT, entry)
    mh = [os.path.join(p, f) for f in os.listdir(p) if f.endswith('.mhmat')] if os.path.isdir(p) else ([p] if entry.endswith('.mhmat') else [])
    if not mh:
        continue
    eid = entry[:-6] if entry.endswith('.mhmat') else entry
    tex = texture_of(mh[0])
    if not tex or not os.path.exists(tex):
        print('no texture', eid)
        continue
    im = Image.open(tex).convert('RGBA')
    im.save(os.path.join(OUT, eid + '.webp'), 'WEBP', quality=84, method=6)
    W, H = im.size
    r = int(0.135 * W)
    cx, cy = int(CENTER[0] * W), int(CENTER[1] * H)
    crop = im.crop((cx - r, cy - r, cx + r, cy + r)).resize((ICON, ICON), Image.LANCZOS)
    mask = Image.new('L', (ICON, ICON), 0)
    ImageDraw.Draw(mask).ellipse((1, 1, ICON - 2, ICON - 2), fill=255)
    out = Image.new('RGBA', (ICON, ICON), (0, 0, 0, 0))
    out.paste(crop, (0, 0), mask)
    out.save(os.path.join(OUT, eid + '.icon.webp'), 'WEBP', quality=88)
    info = meta.get(eid, {})
    items.append({'id': eid, 'name': pretty(eid), 'author': info.get('author') or 'MakeHuman', 'license': info.get('license', 'CC0')})

lines = ["// Generated by mpfb/build_eyes.py: do not edit.", "export interface EyeStyle { id: string; name: string; author: string; license: string }", "", "export const EYE_STYLES: EyeStyle[] = ["]
for it in items:
    lines.append("  { id: %s, name: %s, author: %s, license: %s }," % tuple(json.dumps(it[k], ensure_ascii=False).replace('"', "'") for k in ('id', 'name', 'author', 'license')))
lines += ["];", "", "export const eyeStyleUrl = (id: string) => `/models/eyes/${id}.webp`;", "export const eyeStyleIcon = (id: string) => `/models/eyes/${id}.icon.webp`;", ""]
open(os.path.join(ROOT, 'src', 'constants', 'eyes.ts'), 'w').write('\n'.join(lines))
print(len(items), 'eye styles', sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT)) // 1024, 'KB')
