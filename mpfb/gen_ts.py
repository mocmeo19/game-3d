"""
Writes src/constants/assets.ts and src/constants/skins.ts from the manifests produced by build_assets.py / build_skins.py.

    python3 mpfb/gen_ts.py
"""
import json, os, glob, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
M = os.path.join(ROOT, 'public', 'models')

merged = {}
for g in ('female', 'male'):
    p = os.path.join(M, 'assets', f'manifest.{g}.json')
    if not os.path.exists(p):
        continue
    for aid, e in json.load(open(p)).items():
        cur = merged.setdefault(aid, {**{k: e[k] for k in ('id', 'slot', 'name', 'category', 'author', 'license')}, 'genders': [], 'color': e.get('color', '#9aa4b2')})
        cur['genders'].append(g)
        if e.get('color'):
            cur['color'] = e['color']

order = ['hair', 'eyebrows', 'eyelashes', 'outfit', 'top', 'pants', 'skirt', 'socks', 'shoes', 'hat', 'jewelry', 'accessory', 'glasses', 'horns', 'wings', 'tail', 'nails', 'teeth', 'beard', 'underwear_top', 'underwear_bottom', 'gloves']
items = sorted(merged.values(), key=lambda v: (order.index(v['slot']), v['name'].lower()))


def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


lines = ["  { id: %s, slot: %s, name: %s, category: %s, author: %s, license: %s, genders: %s, color: %s }" % (
    q(v['id']), q(v['slot']), q(v['name']), q(v['category']), q(v['author']), q(v['license']),
    json.dumps(v['genders']).replace('"', "'"), q(v['color'])) for v in items]

ts = """// Generated by mpfb/gen_ts.py from public/models/assets/manifest.<gender>.json. Do not edit by hand.
export type SlotId = 'hair' | 'eyebrows' | 'eyelashes' | 'outfit' | 'top' | 'pants' | 'skirt' | 'socks' | 'shoes' | 'hat' | 'jewelry' | 'accessory' | 'glasses' | 'horns' | 'wings' | 'tail' | 'nails' | 'teeth' | 'beard' | 'underwear_top' | 'underwear_bottom' | 'gloves';
export type AssetGender = 'female' | 'male';

export interface AssetInfo {
  id: string;
  slot: SlotId;
  name: string;
  category: string;
  author: string;
  license: string;
  genders: AssetGender[];
  /** Average colour of the original texture: the default tint. */
  color: string;
}

export const ASSETS: AssetInfo[] = [
%s
];
""" % ",\n".join(lines)
open(os.path.join(ROOT, 'src', 'constants', 'assets.ts'), 'w', encoding='utf-8').write(ts)

skins = json.load(open(os.path.join(M, 'skins', 'manifest.json'))) if os.path.exists(os.path.join(M, 'skins', 'manifest.json')) else []
sk = "// Generated by mpfb/gen_ts.py from public/models/skins/manifest.json. Do not edit by hand.\nexport interface SkinInfo {\n  id: string;\n  name: string;\n  gender: 'female' | 'male' | 'both';\n  color: string;\n  warning?: string;\n}\n\nexport const SKINS: SkinInfo[] = [\n" + ",\n".join(
    "  { id: %s, name: %s, gender: %s, color: %s%s }" % (q(s['id']), q(s['name'] if s['name'] != 'Hoạt hình' else 'Kiểu ' + s['id'].replace('_', ' ').strip().capitalize()), q(s['gender']), q(s['color']), ', warning: ' + q(s['warning']) if s.get('warning') else '') for s in skins) + "\n];\n"
open(os.path.join(ROOT, 'src', 'constants', 'skins.ts'), 'w', encoding='utf-8').write(sk)

# credits: every CC-BY author whose assets are shipped
credits = {}
for v in items:
    if v['license'] != 'CC0':
        credits.setdefault(v['author'], set()).add(v['license'])
# eye styles (src/constants/eyes.ts, written by build_eyes.py)
eyes_ts = os.path.join(ROOT, 'src', 'constants', 'eyes.ts')
if os.path.exists(eyes_ts):
    for au, li in re.findall(r"author: '([^']*)', license: '([^']*)'", open(eyes_ts, encoding='utf-8').read()):
        if li != 'CC0':
            credits.setdefault(au, set()).add(li)
weap_ts = os.path.join(ROOT, 'src', 'constants', 'weaponModels.ts')
if os.path.exists(weap_ts):
    for au, li in re.findall(r"author: '([^']*)', license: '([^']*)'", open(weap_ts, encoding='utf-8').read()):
        if li != 'CC0':
            credits.setdefault(au, set()).add(li)
json.dump({a: sorted(l) for a, l in sorted(credits.items())}, open(os.path.join(ROOT, 'public', 'models', 'credits.json'), 'w'), ensure_ascii=False, indent=1)
print(len(items), 'assets,', len(skins), 'skins,', len(credits), 'credited authors')
